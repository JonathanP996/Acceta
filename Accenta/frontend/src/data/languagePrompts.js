/**
 * Get test prompts for a specific language
 */
export const getTestPrompts = (languageId) => {
  return LANGUAGE_PROMPTS[languageId]?.testPrompts || LANGUAGE_PROMPTS.english.testPrompts;
};

/**
 * Get practice phrases for a specific language
 */
export const getPracticePhrases = (languageId) => {
  return LANGUAGE_PROMPTS[languageId]?.practicePhrases || LANGUAGE_PROMPTS.english.practicePhrases;
};

/**
 * Get struggle area phrases for a specific language
 */
export const getStruggleAreaPhrases = (languageId, struggleArea) => {
  const phrases = LANGUAGE_PROMPTS[languageId]?.struggleAreaPhrases?.[struggleArea.toLowerCase()];
  if (phrases) {
    return phrases;
  }
  // Fallback to English if language doesn't have specific phrases for this struggle area
  return LANGUAGE_PROMPTS.english.struggleAreaPhrases[struggleArea.toLowerCase()] || [];
};

